// Keep payment QR URLs on iPaymu HTTPS hosts; never send EMV payloads to third-party QR APIs.
const TRUSTED_IPAYMU_HOSTS = new Set(['sandbox.ipaymu.com', 'my.ipaymu.com']);

export function trustedIpaymuUrl(raw) {
    if (typeof raw !== 'string' || raw.trim() === '') return null;
    try {
        const parsed = new URL(raw);
        if (parsed.protocol !== 'https:' || !TRUSTED_IPAYMU_HOSTS.has(parsed.hostname.toLowerCase())) return null;
        if (parsed.username || parsed.password || (parsed.port && parsed.port !== '443')) return null;
        return parsed.href;
    } catch {
        return null;
    }
}

export function qrImageCandidates(presentation, preferDirect = false) {
    const direct = trustedIpaymuUrl(presentation?.qr_image);
    // This URL is generated by Laravel's route helper, never from the payment provider.
    const proxy = typeof presentation?.qr_proxy_url === 'string' ? presentation.qr_proxy_url.trim() : '';
    const ordered = preferDirect ? [direct, proxy] : [proxy, direct];
    return [...new Set(ordered.filter(Boolean))];
}

export function paymentTemplateUrl(presentation) {
    return trustedIpaymuUrl(presentation?.qr_template);
}
